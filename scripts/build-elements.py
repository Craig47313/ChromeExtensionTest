#!/usr/bin/env python3
"""Build lib/elements.js (the periodic table data) from the `mendeleev` package's SQLite database.

    pip install --target /tmp/m --no-deps mendeleev
    python3 scripts/build-elements.py /tmp/m/mendeleev/elements.db > lib/elements.js

mendeleev is MIT licensed (https://github.com/lmmentel/mendeleev); its data comes from NIST, IUPAC, CRC and others.
"""
import json
import sqlite3
import sys

YEAR = 365.25 * 86400
UNITS = {
    'ysec': 1e-24, 'zsec': 1e-21, 'asec': 1e-18, 'psec': 1e-12, 'nsec': 1e-9, 'usec': 1e-6, 'msec': 1e-3, 'sec': 1,
    'minute': 60, 'hour': 3600, 'day': 86400, 'year': YEAR, 'kyear': 1e3 * YEAR, 'Myear': 1e6 * YEAR, 'Gyear': 1e9 * YEAR,
    'Tyear': 1e12 * YEAR, 'Pyear': 1e15 * YEAR, 'Eyear': 1e18 * YEAR, 'Zyear': 1e21 * YEAR, 'Yyear': 1e24 * YEAR,
}


# Pauling electronegativities the database leaves empty (values as commonly tabulated, e.g. CRC / Wikipedia).
EN_FILL = {'Kr': 3.0, 'Rn': 2.2, 'Pm': 1.13, 'Eu': 1.2, 'Tb': 1.1, 'Yb': 1.1, 'Am': 1.3, 'Cm': 1.3, 'Bk': 1.3, 'Cf': 1.3, 'Es': 1.3, 'Fm': 1.3, 'Md': 1.3, 'No': 1.3, 'Lr': 1.3}


def r(v, n):
    return None if v is None else round(v, n)


def sig(v, n=4):
    return None if v is None else float(f'{v:.{n}g}')


def main(path):
    c = sqlite3.connect(path)
    series = dict(c.execute('select id, name from series'))
    out = []
    for row in c.execute(
        'select atomic_number, symbol, name, atomic_weight, en_pauling, electronic_configuration, series_id, period, block, '
        'density, electron_affinity, atomic_radius, discovery_year, is_radioactive, group_id from elements order by atomic_number'
    ):
        z, sym, name, mass, en, cfg, sid, period, block, dens, ea, rad, yr, radio, group = row
        pt = c.execute('select melting_point, boiling_point from phasetransitions where atomic_number=? order by (allotrope is not null), id', (z,)).fetchall()
        mp = next((p[0] for p in pt if p[0] is not None), None)
        bp = next((p[1] for p in pt if p[1] is not None), None)
        ie = c.execute('select ionization_energy from ionizationenergies where atomic_number=? and ion_charge=0', (z,)).fetchone()
        ox = sorted({o[0] for o in c.execute("select oxidation_state from oxidationstates where atomic_number=? and category='main'", (z,))}, reverse=True)
        iso = []
        for a, m, ab, rd, hl, unit, spin in c.execute(
            'select mass_number, mass, abundance, is_radioactive, half_life, half_life_unit, spin from isotopes where atomic_number=? order by mass_number', (z,)
        ):
            sec = None if hl is None or unit not in UNITS else sig(hl * UNITS[unit], 4)
            if not rd and hl is None and ab:
                sec = 0  # stable (the database leaves unmeasured short-lived isotopes unflagged, so require a natural abundance)
            iso.append([a, r(m, 6), sig(ab, 5), sec, spin])
        out.append({
            'z': z, 's': sym, 'n': name, 'm': sig(mass, 8), 'en': en if en is not None else EN_FILL.get(sym), 'cfg': cfg, 'cat': series.get(sid), 'per': period, 'blk': block,
            'd': sig(dens, 4), 'mp': sig(mp, 5), 'bp': sig(bp, 5), 'ie': sig(ie[0], 5) if ie else None, 'ea': sig(ea, 4), 'r': rad,
            'ox': ox, 'yr': yr, 'rad': bool(radio), 'iso': iso,
        })
    body = json.dumps(out, separators=(',', ':'), ensure_ascii=False)
    print('// Generated by scripts/build-elements.py from the mendeleev package (MIT; data from NIST, IUPAC and others). Do not edit.')
    print('// Fields: z number, s symbol, n name, m atomic mass (u), en Pauling electronegativity, cfg electron configuration,')
    print('// cat category, per period, blk block, d density (g/cm³), mp/bp melting/boiling point (K), ie first ionisation energy (eV),')
    print('// ea electron affinity (eV), r atomic radius (pm), ox oxidation states, yr year discovered, rad radioactive,')
    print('// iso isotopes as [mass number, mass (u), abundance %, half-life in seconds (0 = stable, null = unknown), spin].')
    print('(function (root) {')
    print('  root.InkElements = ' + body + ';')
    print("})(typeof self !== 'undefined' ? self : globalThis);")


main(sys.argv[1])
